function table(headers, rows, widths) {
  const head = new TableRow({
    children: headers.map((h, i) => cell(h, widths[i], { bold: true, color: WHITE, fill: NAVY })),
  });
  const body = rows.map((r, ri) =>
    new TableRow({
      children: r.map((c, i) => cell(String(c), widths[i], { fill: ri % 2 === 0 ? CARD : WHITE })),
    }),
  );
  return new Table({
    width: { size: CONTENT, type: WidthType.DXA },
    columnWidths: widths,
    rows: [head, ...body],
  });
}

